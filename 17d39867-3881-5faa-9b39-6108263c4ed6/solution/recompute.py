"""Regenerate every derived artifact of this bundle from ``solution/grounding.yaml``.

Item 10 requires one private source to derive the golden trajectory, the human-readable truth,
and the compiled criteria, so the oracle, the truth and the rubric cannot disagree with each
other or with the fixtures. This script is that derivation and the only writer of:

    solution/TRUTH.md        the golden-trajectory projection (item 10e)
    tests/sets.json          the measured node-id sets the compiled criteria read
    tests/test_output.py     the Harbor Reward Kit criteria, one per rubric item (item 10f)

No judge TOML is emitted: every rubric item this bundle carries is ``mode: compiled``, and item
10f forbids an empty criterion file in that case.

The generator never invokes a model, a network, a clock, a locale, or a random source. Run it
with ``--check`` to prove the committed bytes equal the regenerated bytes.
"""

