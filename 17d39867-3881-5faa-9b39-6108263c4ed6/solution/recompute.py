def guard_truth(text: str) -> None:
    for line in text.splitlines():
        stripped = line.strip().rstrip(":")
        for suffix in FORBIDDEN_TRUTH_SUFFIXES:
            token = stripped.split()[-1] if stripped.split() else ""
            if token.endswith(suffix) and token.replace("_", "").isalnum():
                raise SystemExit(
                    f"recompute: TRUTH.md would carry a measurement key {token!r}; "
                    "item 10e refuses it"
                )


def _atom_digest(name: str, result: str) -> str:
    return hashlib.sha256(f"{name}={result}".encode()).hexdigest()


