def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="prove the committed bytes equal the regenerated bytes; write nothing",
    )
    args = parser.parse_args()

    grounding = load()
    drifted: list[str] = []
    for relative, render in TARGETS.items():
        text = render(grounding)
        if relative.endswith("TRUTH.md"):
            guard_truth(text)
        path = ROOT / relative
        if args.check:
            current = path.read_text(encoding="utf-8") if path.exists() else None
            if current != text:
                drifted.append(relative)
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        print(f"recompute: wrote {relative}")

    if args.check:
        if drifted:
            for relative in drifted:
                print(f"recompute: REGENERATION DRIFT {relative}", file=sys.stderr)
            return 1
        print("recompute: no regeneration drift")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
